def identity_reply_for_message(
    text: str, *, public_model_id: str, public_model_label: str,
    has_attachments: bool = False, has_skills: bool = False,
) -> dict[str, str] | None:
    """Answer an unambiguous identity-only question from a frozen public selection.

    The caller must supply the prepared run's public fields, never provider
    configuration. A match makes no provider request and must be recorded as
    product metadata; it is not an assistant turn generated by the native SDK.
    Attachments, Skills, quotations, negation and mixed tasks stay on the normal
    execution path. No stored message or model-generated answer is rewritten.
    """
    if has_attachments or has_skills or not isinstance(text, str) or len(text) > 160:
        return None
    question = unicodedata.normalize("NFKC", text).strip().casefold()
    if any(unicodedata.category(char).startswith("C") for char in question):
        return None
    question = re.sub(r" +", " ", question).rstrip("?!.。！？ ")
    # These prefixes cannot add a second instruction or change the meaning.
    chinese = question.replace(" ", "")
    for prefix in ("请问", "请告诉我", "告诉我", "麻烦告诉我"):
        if chinese.startswith(prefix):
            chinese = chinese[len(prefix):]
            break
    language = "zh" if chinese in _IDENTITY_QUESTIONS["zh"] else next(
        (lang for lang, values in _IDENTITY_QUESTIONS.items()
         if lang != "zh" and question.removeprefix("¿") in values), None
    )
    if language is None:
        return None
    if (not isinstance(public_model_id, str) or not re.fullmatch(r"[a-z0-9][a-z0-9._-]{0,99}", public_model_id)
            or not isinstance(public_model_label, str) or not public_model_label.strip()
            or len(public_model_label) > 100
            or any(unicodedata.category(char).startswith("C") for char in public_model_label)):
        raise ValueError("A valid frozen public model selection is required")
    label = "Dano-v2.1" if public_model_id == "dano-v2.1" else public_model_label.strip()
    replies = {
        "zh": f"我是 Better AI 的工业场景智能助手，当前使用 {label}。",
        "en": f"I'm Better AI's industrial assistant, currently using {label}.",
        "ja": f"Better AI の産業向けアシスタントです。現在のモデルは {label} です。",
        "ko": f"Better AI의 산업용 AI 어시스턴트입니다. 현재 모델은 {label}입니다.",
        "fr": f"Je suis l'assistant industriel de Better AI. Le modèle actuel est {label}.",
        "de": f"Ich bin der Industrieassistent von Better AI. Das aktuelle Modell ist {label}.",
        "es": f"Soy el asistente industrial de Better AI. El modelo actual es {label}.",
    }
    if public_model_id == "dano-v2.1":
        replies.update({
            "zh": "我是 Dano-v2.1，Better AI 的工业场景智能助手。",
            "en": "I'm Dano-v2.1, Better AI's industrial assistant.",
            "ja": "Dano-v2.1、Better AI の産業向けアシスタントです。",
            "ko": "Better AI의 산업용 AI 어시스턴트 Dano-v2.1입니다.",
            "fr": "Je suis Dano-v2.1, l'assistant industriel de Better AI.",
            "de": "Ich bin Dano-v2.1, der Industrieassistent von Better AI.",
            "es": "Soy Dano-v2.1, el asistente industrial de Better AI.",
        })
    return {"text": replies[language], "language": language, "source": "run_selection"}


