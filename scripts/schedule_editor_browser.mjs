/** Verify the same editor from global and per-session management on loopback. */
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_CORE_PATH);
const base=process.env.FEEDBACK_TEST_URL;
assert.equal(new URL(base).hostname,'127.0.0.1');
const root=base+'/project/kaiwu/',api=root+'api/v1';
const browser=await chromium.launch({executablePath:process.env.BROWSER_EXECUTABLE,headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
const checks=[];
async function json(response,status){assert.equal(response.status(),status,await response.text());return response.json();}
try{
  const context=await browser.newContext();
  await json(await context.request.post(api+'/auth/login',{data:{username:'reporter',password:'Correct-test-password-123'}}),200);
  const a=await json(await context.request.post(api+'/assistants',{data:{name:'Editor fixture',instructions:'Synthetic only',connections:[]}}),201);
  const c=await json(await context.request.post(api+'/conversations',{data:{assistant_id:a.id}}),201);
  const route=api+'/conversations/'+c.id+'/schedules';
  const s=await json(await context.request.post(route,{data:{text:'Original synthetic plan',recurrence:'daily',scheduled_at:new Date(Date.now()+3600000).toISOString()}}),201);
  const before=(await json(await context.request.get(route),200)).find(r=>r.id===s.id);
  const page=await context.newPage();
  const sends=[];
  page.on('request',r=>{if(r.method()==='POST'&&/\/messages$/.test(new URL(r.url()).pathname))sends.push(r.url());});
  await page.goto(root);
  await page.getByRole('button',{name:'定时任务',exact:true}).click({timeout:20000});
  const row=page.locator('.approval-card').filter({hasText:'Original synthetic plan'});
  await row.getByRole('button',{name:'编辑',exact:true}).click();
  const modal=page.getByRole('dialog',{name:'编辑定时任务'});
  await modal.getByLabel('任务内容').fill('Edited synthetic plan');
  const [res]=await Promise.all([page.waitForResponse(r=>r.request().method()==='PATCH'&&r.url()===route+'/'+s.id),modal.getByRole('button',{name:'保存修改'}).click()]);
  const edited=await json(res,200);
  assert.equal(edited.scheduled_at,before.scheduled_at);
  assert.notEqual(edited.edit_token,before.edit_token);
  const changed=page.locator('.approval-card').filter({hasText:'Edited synthetic plan'});
  await changed.waitFor();
  checks.push('global editor saves text without retiming');
  assert.equal((await context.request.patch(route+'/'+s.id,{data:{text:'stale overwrite',expected_token:before.edit_token}})).status(),409);
  checks.push('stale UI token rejected');
  await changed.getByRole('button',{name:'打开关联会话'}).click();
  await page.waitForURL(u=>u.searchParams.get('conversation')===c.id);
  await page.getByRole('button',{name:'问题反馈',exact:true}).waitFor();
  const sidebar=page.getByRole('button',{name:'会话侧栏',exact:true});
  if(await sidebar.getAttribute('aria-expanded')!=='true')await sidebar.click();
  const edit=page.locator('.task-sidebar-schedule-row').filter({hasText:'Edited synthetic plan'}).getByRole('button',{name:'编辑',exact:true});
  await edit.click();
  await modal.getByLabel('任务内容').fill('Edited in conversation');
  const [saved]=await Promise.all([page.waitForResponse(r=>r.request().method()==='PATCH'&&r.url()===route+'/'+s.id),modal.getByRole('button',{name:'保存修改'}).click()]);
  assert.equal((await json(saved,200)).text,'Edited in conversation');
  assert.equal(sends.length,0);
  checks.push('conversation uses same editor and no model call');
  console.log(JSON.stringify({passed:checks.length,checks}));
}finally{await browser.close();}
